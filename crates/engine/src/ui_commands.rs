/// Exact registry lookup: unknown ids must remain unknown command errors.
pub fn is_ui_command(id: &str) -> bool {
    UI_COMMANDS.iter().any(|c| c.0 == id)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn ids_are_unique_and_classification_is_exact() {
        let mut ids = std::collections::HashSet::new();
        for c in UI_COMMANDS {
            assert!(ids.insert(c.0), "{}", c.0);
            assert!(is_ui_command(c.0));
        }
        for id in ["app.unknown", "view.zoomTypo", "window.fake", "ai.notRegistered", "file.new"] {
            assert!(!is_ui_command(id), "{id}");
        }
        assert!(is_ui_command("effects.dialog"));
        assert!(is_ui_command("help.about"));
    }
}
